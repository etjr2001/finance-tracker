-- Favourite: a manual template for prefilling a new Transaction (ADR0017).
-- Mirrors transactions' type/amount/note rules, minus the date. user_id has
-- no FK and there's no RLS, same as V1.
--
-- category_id has no ON DELETE action, so the default blocks deleting a
-- Category a Favourite still uses. CategoryService checks first and returns
-- a friendly CategoryInUseException; the FK is the backstop if that check
-- is ever missed.
--
-- amount stays numeric(12,2) to match transactions.amount. Both get widened
-- together when Currency is built (docs/backlog.md).
--
-- No NOT VALID on the checks: the table is new and empty.
create table favourites (
    id          bigint generated by default as identity primary key,
    user_id     uuid not null,
    category_id bigint not null references categories(id),
    type        text not null
                constraint chk_favourites_type check (type in ('EXPENSE', 'INCOME')),
    amount      numeric(12, 2) not null
                constraint chk_favourites_amount_non_negative check (amount >= 0),
    note        text
                constraint chk_favourites_note_length check (char_length(note) <= 256),
    created_at  timestamptz not null default now()
);

create index idx_favourites_user on favourites(user_id);
-- Backs FavouriteRepository.existsByCategoryId and the FK check on
-- Category delete, which would otherwise scan favourites.
create index idx_favourites_category on favourites(category_id);
